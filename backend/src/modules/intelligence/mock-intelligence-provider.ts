import type { IntelligenceRequest } from "./contracts/intelligence-engine.js";
import type { IntelligenceProvider } from "./contracts/intelligence-provider.js";

export class MockIntelligenceProvider implements IntelligenceProvider {
  public async generate(request: IntelligenceRequest): Promise<string> {
    const message = request.messages.at(-1)?.content ?? "";
    const normalized = message.replace(/\s+/g, " ").trim();

    if (/تولد/u.test(normalized)) {
      return [
        "دوست خوبم،",
        "",
        "تولدت مبارک! برایت سالی سرشار از سلامتی، آرامش، شادی و اتفاق‌های خوب آرزو می‌کنم. امیدوارم به آرزوهای قشنگت برسی و هر روز دلیلی تازه برای لبخند زدن داشته باشی.",
        "",
        "با بهترین آرزوها،",
        "دوستدار تو",
      ].join("\n");
    }

    if (/فارغ.?التحصیل|دانش.?آموختگ/u.test(normalized)) {
      return [
        "دوست خوبم،",
        "",
        "فارغ‌التحصیلی‌ات را صمیمانه تبریک می‌گویم. این موفقیت حاصل تلاش، پشتکار و اراده توست. امیدوارم این دستاورد آغاز فصل تازه‌ای از پیشرفت، فرصت‌های خوب و موفقیت‌های بزرگ‌تر در زندگی‌ات باشد.",
        "",
        "با آرزوی آینده‌ای روشن،",
        "دوستدار تو",
      ].join("\n");
    }

    if (/تبریک/u.test(normalized)) {
      return [
        "موضوع: تبریک و آرزوی موفقیت",
        "",
        "دوست خوبم،",
        "",
        "موفقیتت را صمیمانه تبریک می‌گویم. این دستاورد نشان‌دهنده تلاش، پشتکار و توانایی توست. امیدوارم این موفقیت آغاز راهی پربار باشد و در ادامه مسیر نیز فرصت‌های خوب، شادی و پیشرفت بیشتری نصیبت شود.",
        "",
        "با بهترین آرزوها،",
        "دوستدار تو",
      ].join("\n");
    }

    if (/تشکر|قدردان/u.test(normalized)) {
      return [
        "دوست خوبم،",
        "",
        "می‌خواهم از لطف، همراهی و محبتی که نشان دادی صمیمانه تشکر کنم. توجه و حمایتت برایم ارزشمند است و از اینکه در کنارم بودی، قدردانم.",
        "",
        "با سپاس و احترام،",
        "دوستدار تو",
      ].join("\n");
    }

    return "نوا در حال حاضر به موتور هوش مصنوعی متصل نیست؛ بنابراین نمی‌خواهم پاسخ ساختگی یا نامطمئن بدهم. لطفاً کمی بعد دوباره تلاش کنید.";
  }
}
